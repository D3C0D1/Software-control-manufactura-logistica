            <h2>Definiciones</h2>
            <ul>
                <li><strong>Petición:</strong> Es una solicitud de información sobre nuestros productos, servicios o cualquier otro aspecto de nuestra empresa.</li>
                <li><strong>Queja:</strong> Es la manifestación de una inconformidad con un producto o con la atención recibida por parte de nuestro personal.</li>
                <li><strong>Reclamo:</strong> Es una oposición o contrariedad presentada con el objetivo de que se revise y se evalúe una acción relacionada con la prestación de nuestros servicios.</li>
                <li><strong>Sugerencia:</strong> Es una propuesta o idea que presentas para mejorar nuestros procesos, productos o servicios.</li>
            </ul>
        </section>

